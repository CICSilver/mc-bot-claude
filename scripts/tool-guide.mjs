export function buildToolGuide(layer) {
  return [
    '---',
    '## Agy CLI 工具调用与参数速查',
    `- 游戏身体工具通过 \`call_mcp_tool\` 调用，\`ServerName\` 填 \`minecraft_${layer}\`，\`ToolName\` 填工具名，\`Arguments\` 直接填写该工具的参数对象。`,
    '- 以下为参数格式示例，坐标、对象、数量和文字按当前现场填写；完整参数与枚举值查阅本层工具 schema。',
    `- 文件工具的 \`ServerName\` 填 \`files_${layer}\`：`,
    '  - `Read`: `{"path": "memory/self.md"}`',
    ...(layer === 'mind' || layer === 'planner' ? [
      '  - `Edit`: `{"path": "memory/goals.md", "old_string": "原文", "new_string": "新内容"}`',
      '  - `AppendJournal`: `{"date": "YYYY-MM-DD", "text": "日记内容"}`；date 按该格式填当前日期。',
    ] : []),
    '- 各层共用的查询参数：',
    '  - `get-status`: `{}` | `get-position`: `{}` | `list-inventory`: `{}` | `get-relationships`: `{}` | `look-around`: `{"radius": 16}`',
    '  - `find-entity`: `{"type": "sheep", "maxDistance": 16}`；type 填生物名或 player，省略时查找任意实体。具体玩家的位置见〔现在〕。',
    '  - `find-item`: `{"nameOrType": "shears"}`；查询背包中的物品。',
    ...(['fast', 'exec'].includes(layer) ? [
      '- 陪伴工具参数：',
      '  - `accompany-player`: `{"username": "玩家名"}` | `follow-player`: `{"username": "玩家名", "distance": 2}` | `stop-following`: `{}`',
    ] : []),
    ...(layer === 'mind' ? [
      '- 调度脑常用工具参数：',
      '  - `get-tasks`: `{}` | `get-todos`: `{}`',
      '  - `survey-terrain`: `{"x1": 0, "z1": 0, "x2": 4, "z2": 4}`；勘测范围内的高度图。',
      '  - `assign-task`: `{"goal": "完整的一件事", "doneWhen": "完成标准", "allowed": "允许使用的材料与范围（写宽松）"}`；关联待办填 todoId，使用图纸填 blueprint，换做法重派时填 changes。',
      '  - `set-todos`: `{"items": [{"title": "小步标题", "doneWhen": "完成标准", "allowed": "范围与材料", "note": "备注"}], "mode": "replace"}`；mode 可选 replace、append。',
      '  - `update-todo`: `{"id": 1, "status": "pending", "note": "进展"}`；status 可选 pending、doing、done、skipped。',
      '  - `cancel-task`: `{"id": 1, "reason": "取消原因"}`',
      '  - `pass-to-mouth`: `{"to": "玩家名", "say": "沟通要点"}`',
      '  - `share-plan`: `{"plan": "打算概要", "waitingFor": "water_bucket x1"}`；waitingFor 可填等待的物品与数量。',
      '  - `change-affinity`: `{"player": "玩家名", "amount": 1, "reason": "原因"}`',
      '  - `feel`: `{"happy": 1, "tense": 0, "who": "玩家名", "reason": "原因"}`',
      '  - `request-plan`: `{"brief": "设计或整理心愿的目标、地点、材料、喜好"}` | `cancel-plan`: `{"reason": "取消原因"}`',
      '  - `stop-work`: `{"action": "pause", "reason": "玩家原话与意图"}` | `resume-work`: `{}`；action 可选 pause、cancel、logout。',
      '  - `logout`: `{"note": "未完事项与下一步"}`；保存本次下线记录并退出。',
    ] : []),
    ...(layer === 'exec' ? [
      '- 执行脑常用工具参数：',
      '  - `get-task`: `{}` | `get-todos`: `{}` | `pick-up-items`: `{"maxDistance": 8}`',
      '  - `find-blocks`: `{"blockType": "iron_ore", "maxDistance": 16, "count": 5}` | `gather-blocks`: `{"blocks": ["iron_ore", "deepslate_iron_ore", "coal_ore"], "count": 12, "radius": 16}`',
      '  - `survey-terrain`: `{"x1": 0, "z1": 0, "x2": 4, "z2": 4}` | `clear-area`: `{"x1": 0, "z1": 0, "x2": 4, "z2": 4, "floorY": 64, "confirmed": false}`；confirmed: false 预览，玩家确认范围与高度后用 confirmed: true 开工。',
      '  - `report-task`: `{"id": 1, "kind": "done", "text": "汇报内容"}`；kind 可选 done、stuck、waiting、failed、progress；stuck、failed 的已尝试方法写在 tried。',
      '  - `move-to-position`: `{"x": 0, "y": 64, "z": 0, "range": 1}`；省略 timeoutMs 时使用身体默认的 60000 毫秒，后台 do-steps 中的移动也使用这个默认值。',
      '  - `move-in-direction`: `{"direction": "forward", "duration": 800, "jump": true}`；direction 可选 forward、back、left、right，duration 单位为毫秒。',
      '  - `open-container`: `{"x": 0, "y": 64, "z": 0}` | `take-item`: `{"x": 0, "y": 64, "z": 0, "item": "oak_log", "count": 1}` | `store-item`: `{"x": 0, "y": 64, "z": 0, "item": "oak_log", "count": 1}` | `equip-item`: `{"itemName": "stone_pickaxe"}`',
      '  - `craft-item`: `{"outputItem": "stick", "amount": 1}`；amount 是合成次数，4 根木棍合成 1 次。`place-block`: `{"x": 0, "y": 64, "z": 0, "block": "oak_planks"}`',
      '  - `make-farm`: `{"x1": 0, "z1": 0, "x2": 4, "z2": 4, "seed": "wheat_seeds", "waterInMiddle": false}`',
      '  - `explore`: `{"direction": "north", "distance": 64, "lookFor": ["sheep"]}` | `go-fishing`: `{"minutes": 5, "catches": 3}`',
      '  - `murmur`: `{"text": "头顶嘀咕文字", "emote": "sparkle"}`',
      '  - `do-steps`: `{"title": "步骤标题", "steps": [{"tool": "move-to-position", "args": {"x": 0, "y": 64, "z": 0, "range": 1}}]}`；每一步的 args 使用对应工具的参数。',
    ] : []),
    ...(layer === 'fast' ? [
      '- 快层常用工具参数，游戏里的话通过 send-chat 发出：',
      '  - `send-chat`: `{"message": "聊天内容", "toward": "玩家名", "emote": "wave"}`',
      '  - `murmur`: `{"text": "头顶自言自语", "emote": "sparkle"}`',
      '  - `look-at`: `{"x": 0, "y": 64, "z": 0}` | `crouch`: `{"times": 2}` | `emote`: `{"name": "wave", "toward": "玩家名"}`',
      '  - `move-to-position`: `{"x": 0, "y": 64, "z": 0, "range": 2, "timeoutMs": 5000}`；快层用于身边的短移动，长途行走交给执行脑。',
      '  - `note-for-later`: `{"note": "记给调度脑的事项", "urgent": true}`',
      '  - `stop-work`: `{"action": "pause", "reason": "玩家原话与意图"}`；action 可选 pause、cancel、logout；玩家叫停或下线时先调用，再回应聊天。',
      '  - `change-affinity`: `{"player": "玩家名", "amount": 1, "reason": "原因"}`',
    ] : []),
    ...(layer === 'planner' ? [
      '- 规划脑常用工具参数：',
      '  - `get-todos`: `{}` | `set-todos`: `{"items": [{"title": "小步标题", "doneWhen": "完成标准", "allowed": "范围与材料", "note": "备注"}], "mode": "replace"}` | `update-todo`: `{"id": 1, "status": "pending", "note": "进展"}`；mode 可选 replace、append；status 可选 pending、doing、done、skipped。',
      '  - `save-blueprint`: `{"name": "图纸名", "x": 0, "y": 64, "z": 0, "palette": {"P": "oak_planks"}, "layers": [["P"]], "note": "说明"}`；x、z 是西北角，y 是底层高度，layers 从下往上排列。',
      '  - `report-plan`: `{"id": 1, "summary": "方案、今日待办或图纸名、材料与分段建议"}`；id 填收到的规划编号，自主整理填 0。',
      '  - `get-block-info`: `{"x": 0, "y": 64, "z": 0}`',
    ] : []),
    '- 文件与世界操作通过本层 MCP 工具完成。',
  ].join('\n');
}
